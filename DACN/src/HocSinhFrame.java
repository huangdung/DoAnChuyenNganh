    private void themHocSinh() {
        if (!"Admin".equalsIgnoreCase(currentRole)) {
            JOptionPane.showMessageDialog(this, "Tài khoản Giáo viên chỉ có quyền Xem & Tra cứu!\nVui lòng đăng nhập tài khoản Quản trị viên (Admin) để thực hiện thao tác Thêm học sinh.", 
                                          "Không Có Quyền", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            String maSinhVien = txtMaSinhVien.getText().trim();
            String hoTen = txtHoTen.getText().trim();
            String ngaySinh = txtNgaySinh.getText().trim();
            String gioiTinh = (String) cbbGioiTinh.getSelectedItem();
            String diaChi = txtDiaChi.getText().trim();
            String tenLop = cbbTenLop.getSelectedItem() != null ? cbbTenLop.getSelectedItem().toString().trim() : "";
            String diemTBStr = txtDiemTB.getText().trim();
            String ngayNhapHoc = txtNgayNhapHoc.getText().trim();
            String trangThai = (String) cbbTrangThai.getSelectedItem();
            String soCMND = txtCMND.getText().trim();

            // 1. Kiểm tra rỗng các trường bắt buộc
            if (maSinhVien.isEmpty() || hoTen.isEmpty() || ngaySinh.isEmpty() || 
                diaChi.isEmpty() || tenLop.isEmpty() || diemTBStr.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ các trường thông tin bắt buộc (*)", 
                                              "Cảnh Báo", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // 2. Ràng buộc Mã học sinh
            if (!maSinhVien.matches("^[a-zA-Z0-9]+$")) {
                JOptionPane.showMessageDialog(this, "Mã học sinh chỉ được chứa chữ cái và chữ số, không chứa khoảng trắng!", 
                                              "Sai Mã Học Sinh", JOptionPane.WARNING_MESSAGE);
                txtMaSinhVien.requestFocus();
                return;
            }
            if (manager.tonTaiMaSinhVien(maSinhVien)) {
                JOptionPane.showMessageDialog(this, "Mã học sinh '" + maSinhVien + "' đã tồn tại trong hệ thống! Vui lòng chọn mã khác.", 
                                              "Trùng Mã Học Sinh", JOptionPane.ERROR_MESSAGE);
                txtMaSinhVien.requestFocus();
                return;
            }

            // 3. Ràng buộc Họ tên
            if (hoTen.length() < 2 || hoTen.matches("^\\d+$")) {
                JOptionPane.showMessageDialog(this, "Họ tên học sinh không hợp lệ!", 
                                              "Sai Họ Tên", JOptionPane.WARNING_MESSAGE);
                txtHoTen.requestFocus();
                return;
            }

            // 4. Ràng buộc Ngày sinh
            java.time.LocalDate birthDate;
            try {
                java.time.format.DateTimeFormatter dtf = java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy");
                birthDate = java.time.LocalDate.parse(ngaySinh, dtf);
                if (birthDate.isAfter(java.time.LocalDate.now())) {
                    JOptionPane.showMessageDialog(this, "Ngày sinh không thể lớn hơn ngày hiện tại!", 
                                                  "Sai Ngày Sinh", JOptionPane.WARNING_MESSAGE);
                    txtNgaySinh.requestFocus();
                    return;
                }
                if (birthDate.isAfter(java.time.LocalDate.now().minusYears(5))) {
                    JOptionPane.showMessageDialog(this, "Độ tuổi học sinh không hợp lý (học sinh phải từ 5 tuổi trở lên)!", 
                                                  "Sai Ngày Sinh", JOptionPane.WARNING_MESSAGE);
                    txtNgaySinh.requestFocus();
                    return;
                }
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Ngày sinh không đúng định dạng chuẩn dd/MM/yyyy (VD: 15/08/2005)!", 
                                              "Sai Định Dạng Ngày Sinh", JOptionPane.WARNING_MESSAGE);
                txtNgaySinh.requestFocus();
                return;
            }

            // 5. Ràng buộc Số CMND/CCCD (chống trùng lặp tuyệt đối)
            if (soCMND.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập số CMND/CCCD của học sinh!", 
                                              "Thiếu CMND/CCCD", JOptionPane.WARNING_MESSAGE);
                txtCMND.requestFocus();
                return;
            }
            if (!soCMND.matches("^\\d{9}$|^\\d{12}$")) {
                JOptionPane.showMessageDialog(this, "Số CMND/CCCD không hợp lệ! Phải gồm đúng 9 chữ số (CMND) hoặc 12 chữ số (CCCD).", 
                                              "Sai Định Dạng CMND/CCCD", JOptionPane.WARNING_MESSAGE);
                txtCMND.requestFocus();
                return;
            }
            if (manager.tonTaiSoCMND(soCMND)) {
                JOptionPane.showMessageDialog(this, "Số CMND/CCCD '" + soCMND + "' đã tồn tại trong hệ thống!\nMỗi học sinh chỉ được có 1 số CMND/CCCD duy nhất.", 
                                              "Trùng CMND/CCCD", JOptionPane.ERROR_MESSAGE);
                txtCMND.requestFocus();
                return;
            }

            // 6. Ràng buộc Ngày nhập học
            if (!ngayNhapHoc.isEmpty()) {
                try {
                    java.time.format.DateTimeFormatter dtf = java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy");
                    java.time.LocalDate enrollDate = java.time.LocalDate.parse(ngayNhapHoc, dtf);
                    if (enrollDate.isBefore(birthDate)) {
                        JOptionPane.showMessageDialog(this, "Ngày nhập học (" + ngayNhapHoc + ") không thể xảy ra trước ngày sinh (" + ngaySinh + ")!", 
                                                      "Sai Ngày Nhập Học", JOptionPane.WARNING_MESSAGE);
                        txtNgayNhapHoc.requestFocus();
                        return;
                    }
                } catch (Exception ex) {
                    JOptionPane.showMessageDialog(this, "Ngày nhập học không đúng định dạng dd/MM/yyyy (VD: 05/09/2023)!", 
                                                  "Sai Định Dạng Ngày Nhập Học", JOptionPane.WARNING_MESSAGE);
                    txtNgayNhapHoc.requestFocus();
                    return;
                }
            }

            // 7. Ràng buộc Điểm TB
            double diemTB = Double.parseDouble(diemTBStr);
            if (diemTB < 0.0 || diemTB > 10.0) {
                JOptionPane.showMessageDialog(this, "Điểm trung bình không hợp lệ! Vui lòng nhập trong khoảng từ 0.0 đến 10.0.", 
                                              "Sai Điểm TB", JOptionPane.WARNING_MESSAGE);
                txtDiemTB.requestFocus();
                return;
            }

            if (trangThai == null || trangThai.isEmpty()) {
                trangThai = "Đang học";
            }

            HocSinh hs = new HocSinh(maSinhVien, hoTen, ngaySinh, gioiTinh, diaChi, tenLop, diemTB, ngayNhapHoc, trangThai, soCMND);
            manager.themHocSinh(hs);
            refreshTable(manager.getDanhSachHocSinh());
            updateCbbLoc();
            updateCbbTenLop();
            clearInputs();
            JOptionPane.showMessageDialog(this, "Thêm học sinh [" + hoTen + "] thành công!", 
                                          "Thành Công", JOptionPane.INFORMATION_MESSAGE);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Điểm trung bình phải là số (VD: 8.5)!", 
                                          "Lỗi Định Dạng", JOptionPane.ERROR_MESSAGE);
            txtDiemTB.requestFocus();
        }
    }

