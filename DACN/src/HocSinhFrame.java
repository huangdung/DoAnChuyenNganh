    private javax.swing.JTable createStatTable(String[] cols, Object[][] data, java.awt.Color headerColor) {
        DefaultTableModel model = new DefaultTableModel(data, cols) {
            @Override
            public boolean isCellEditable(int r, int c) { return false; }
        };
        javax.swing.JTable table = new javax.swing.JTable(model);
        table.setRowHeight(25);
        table.setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 12));
        table.setShowGrid(true);
        table.setGridColor(new java.awt.Color(235, 238, 242));
        table.setSelectionBackground(new java.awt.Color(220, 235, 252));
        table.setSelectionForeground(new java.awt.Color(30, 41, 59));
        table.getTableHeader().setReorderingAllowed(false);
        table.setDefaultEditor(Object.class, null);

        javax.swing.table.DefaultTableCellRenderer centerRenderer = new javax.swing.table.DefaultTableCellRenderer();
        centerRenderer.setHorizontalAlignment(javax.swing.JLabel.CENTER);
        for (int i = 0; i < table.getColumnCount(); i++) {
            table.getColumnModel().getColumn(i).setCellRenderer(centerRenderer);
        }

        table.getTableHeader().setDefaultRenderer(new javax.swing.table.DefaultTableCellRenderer() {
            @Override
            public java.awt.Component getTableCellRendererComponent(javax.swing.JTable tbl, Object val,
                    boolean isSel, boolean hasFoc, int row, int col) {
                java.awt.Component comp = super.getTableCellRendererComponent(tbl, val, isSel, hasFoc, row, col);
                comp.setBackground(headerColor);
                comp.setForeground(java.awt.Color.WHITE);
                comp.setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 11));
                ((javax.swing.JLabel) comp).setHorizontalAlignment(javax.swing.JLabel.CENTER);
                ((javax.swing.JComponent) comp).setBorder(javax.swing.BorderFactory.createMatteBorder(0, 0, 1, 1, new java.awt.Color(215, 220, 225)));
                return comp;
            }
        });
        return table;
    }

