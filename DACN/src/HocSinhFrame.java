    private void updateCbbLoc() {
        List<String> danhSachLop = manager.getDanhSachLop();
        danhSachLop.add(0, "Tất cả"); 
        cbbLoc.setModel(new javax.swing.DefaultComboBoxModel<>(danhSachLop.toArray(new String[0])));
    }

    private void updateCbbTenLop() {
        java.util.Set<String> setLop = new java.util.TreeSet<>();
        setLop.add("10A1"); setLop.add("10A2"); setLop.add("10A3");
        setLop.add("11A1"); setLop.add("11A2"); setLop.add("11A3");
        setLop.add("12A1"); setLop.add("12A2"); setLop.add("12A3");
        if (manager != null && manager.getDanhSachHocSinh() != null) {
            for (HocSinh hs : manager.getDanhSachHocSinh()) {
                if (hs.getTenLop() != null && !hs.getTenLop().trim().isEmpty()) {
                    setLop.add(hs.getTenLop().trim());
                }
            }
        }
        Object current = cbbTenLop.getSelectedItem();
        cbbTenLop.setModel(new javax.swing.DefaultComboBoxModel<>(setLop.toArray(new String[0])));
        cbbTenLop.setEditable(true);
        if (current != null && !current.toString().trim().isEmpty()) {
            cbbTenLop.setSelectedItem(current.toString().trim());
        }
    }
